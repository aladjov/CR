class MarkdownDriftRenderer(DriftReportRenderer):
    def join_sections(self, sections: Iterable[str]) -> str:
        return "\n\n".join(s for s in sections if s) + "\n"

    def render_title(self) -> str:
        return f"# Drift Report: {self.drift.old_meta.sha} -> {self.drift.new_meta.sha}"

    def render_summary(self) -> str:
        d = self.drift
        old_nb = len(d.old_manifest.notebooks)
        new_nb = len(d.new_manifest.notebooks)
        return (
            f"## Summary\n"
            f"- Old: {d.old_meta.label}\n"
            f"- New: {d.new_meta.label}\n"
            f"- Notebooks captured: {old_nb} (old), {new_nb} (new)"
        )

    def _status_icon(self, status: str) -> str:
        return {"OK": "\u2705", "FAILED": "\u274c", "ERROR": "\u26a0\ufe0f", "SKIPPED": "\u23ed", "N/A": "\u2014"}.get(status, status)

    def render_section_map_changes(self) -> str:
        rows = ["| Notebook | Old status | New status | Old cells (outputs) | New cells (outputs) | Cell delta | Output delta |",
                "|----------|-----------|-----------|--------------------|--------------------|------------|--------------|"]
        for nb, ((oc, oo), (nc, no)) in self.section_map_parsed().items():
            old_st, new_st = self.notebook_run_status(nb)
            cd = nc - oc if oc or nc else "N/A"
            od = no - oo if oc or nc else "N/A"
            rows.append(f"| {nb} | {self._status_icon(old_st)} {old_st} | {self._status_icon(new_st)} {new_st} | {oc} ({oo}) | {nc} ({no}) | {cd} | {od} |")
        return "## Section Map Changes\n\n" + "\n".join(rows)

    def render_model_metrics(self) -> str:
        data = self.metric_comparison_data()
        if not data:
            return "## Model Metrics (NB08)\n\n_No metric tables found in either run._"
        parts = ["## Model Metrics (NB08)"]
        for entry in data:
            if entry["merged_df"] is not None:
                parts.append(entry["merged_df"].to_markdown(index=False))
                for w in entry["warnings"]:
                    parts.append(f"\n\u26a0 **{w}**")
            elif entry["old_df"] is not None:
                parts.append(f"**Old only ({entry['old_name']}):**\n{entry['old_df'].to_markdown(index=False)}")
            elif entry["new_df"] is not None:
                parts.append(f"**New only ({entry['new_name']}):**\n{entry['new_df'].to_markdown(index=False)}")
        return "\n\n".join(parts)

    def _render_yaml_section(self, title: str, old_d: Optional[dict], new_d: Optional[dict], keys: list[str], extra: str = "") -> str:
        if old_d is None and new_d is None:
            return f"## {title}\n\n_Not available._"
        rows = ["| Parameter | Old | New | Changed |", "|-----------|-----|-----|---------|"]
        for key, ov, nv, changed in self.yaml_diff_rows(old_d, new_d, keys):
            flag = "\u26a0" if changed else ""
            rows.append(f"| {key} | {ov} | {nv} | {flag} |")
        result = f"## {title}\n\n" + "\n".join(rows)
        if extra:
            result += f"\n\n{extra}"
        return result

    def render_snapshot_grid(self) -> str:
        return self._render_yaml_section(
            "Snapshot Grid", self.drift.snapshot_grid_old, self.drift.snapshot_grid_new,
            self.SNAPSHOT_GRID_KEYS, self.grid_dates_summary() or "",
        )

    def render_project_context(self) -> str:
        return self._render_yaml_section(
            "Project Context / Intent", self.drift.project_context_old, self.drift.project_context_new,
            self.PROJECT_CONTEXT_KEYS,
        )

    def render_feature_profile(self) -> str:
        added, removed, common = self.feature_profile_sets()
        if not added and not removed and not common:
            return "## Feature Profile\n\n_Not found in either run._"
        parts = [
            "## Feature Profile",
            f"- Old features: {len(removed) + len(common)}",
            f"- New features: {len(added) + len(common)}",
            f"- Added: {len(added)}, Removed: {len(removed)}, Common: {len(common)}",
        ]
        if added:
            parts.append(f"\n**Added:** {', '.join(sorted(added)[:20])}")
        if removed:
            parts.append(f"\n**Removed:** {', '.join(sorted(removed)[:20])}")
        return "\n".join(parts)

    def render_timing(self) -> str:
        ot, nt = self.drift.old_timings, self.drift.new_timings
        if not ot and not nt:
            return "## Per-Notebook Timing\n\n_No timing logs found._"
        rows = ["| Notebook | Old | New | Delta |", "|----------|-----|-----|-------|"]
        for nb in dict.fromkeys(list(ot) + list(nt)):
            ov, nv = ot.get(nb, "N/A"), nt.get(nb, "N/A")
            try:
                delta = f"{float(nv) - float(ov):+.1f}s"
            except (ValueError, TypeError):
                delta = "N/A"
            rows.append(f"| {nb} | {ov} | {nv} | {delta} |")
        return "## Per-Notebook Timing\n\n" + "\n".join(rows)

    def render_cell_by_cell_diff(self) -> str:
        parts = ["## Cell-by-Cell Diff"]
        any_diff = False
        for nd in self.drift.notebook_drifts:
            old_st, new_st = self.notebook_run_status(nd.notebook_name)
            old_time, new_time = self.notebook_timing(nd.notebook_name)
            old_part = f"{self._status_icon(old_st)} {old_st} ({old_time})" if old_time else f"{self._status_icon(old_st)} {old_st}"
            new_part = f"{self._status_icon(new_st)} {new_st} ({new_time})" if new_time else f"{self._status_icon(new_st)} {new_st}"
            status_line = f"Old: {old_part} | New: {new_part}"
            if not nd.has_changes:
                continue
            any_diff = True
            nb_parts = [f"---\n\n### {nd.notebook_name}\n\n> {status_line}"]
            for m in nd.changed_matches:
                name = (m.new_cell or m.old_cell).name
                label = m.status.value.upper()
                nb_parts.append(f"#### {name} ({label})")
                if m.status == CellMatchStatus.ADDED:
                    nb_parts.append(f"```\n{m.new_cell.content[:_CELL_CONTENT_MAX]}\n```")
                elif m.status == CellMatchStatus.REMOVED:
                    nb_parts.append(f"```\n{m.old_cell.content[:_CELL_CONTENT_MAX]}\n```")
                elif m.diff_text:
                    nb_parts.append(f"```diff\n{m.diff_text}\n```")
                elif m.status == CellMatchStatus.RENAMED:
                    nb_parts.append(f"_Renamed from `{m.old_cell.name}` to `{m.new_cell.name}`_")
            parts.append("\n\n".join(nb_parts))
        if not any_diff:
            parts.append("_No cell-level differences detected._")
        return "\n\n".join(parts)


