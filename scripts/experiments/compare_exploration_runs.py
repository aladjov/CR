class DriftReportRenderer(ABC):
    REPORT_SECTIONS = [
        "title",
        "summary",
        "section_map_changes",
        "model_metrics",
        "snapshot_grid",
        "project_context",
        "feature_profile",
        "timing",
        "cell_profiling",
        "cell_by_cell_diff",
    ]
    SNAPSHOT_GRID_KEYS = [
        "grid_start",
        "grid_end",
        "cadence_interval",
        "observation_window_days",
        "purge_gap_days",
        "label_window_days",
        "max_grid_dates",
    ]
    PROJECT_CONTEXT_KEYS = [
        "prediction_horizons",
        "recent_window_days",
        "observation_window_days",
        "purge_gap_days",
        "label_window_days",
        "split_strategy",
        "cadence_interval",
        "temporal_posture",
    ]

    def __init__(self, drift: DriftResult):
        self.drift = drift

    def render(self) -> str:
        return self.join_sections(getattr(self, f"render_{s}")() for s in self.REPORT_SECTIONS)

    def write(self, path: Path) -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(self.render(), encoding="utf-8")

    @abstractmethod
    def join_sections(self, sections: Iterable[str]) -> str: ...

    @abstractmethod
    def render_title(self) -> str: ...

    @abstractmethod
    def render_summary(self) -> str: ...

    @abstractmethod
    def render_section_map_changes(self) -> str: ...

    @abstractmethod
    def render_model_metrics(self) -> str: ...

    @abstractmethod
    def render_snapshot_grid(self) -> str: ...

    @abstractmethod
    def render_project_context(self) -> str: ...

    @abstractmethod
    def render_feature_profile(self) -> str: ...

    @abstractmethod
    def render_timing(self) -> str: ...

    @abstractmethod
    def render_cell_profiling(self) -> str: ...

    @abstractmethod
    def render_cell_by_cell_diff(self) -> str: ...

    def yaml_diff_rows(
        self, old: Optional[dict], new: Optional[dict], keys: list[str]
    ) -> list[tuple[str, str, str, bool]]:
        rows = []
        for key in keys:
            old_val = str(old.get(key, "N/A")) if old else "N/A"
            new_val = str(new.get(key, "N/A")) if new else "N/A"
            rows.append((key, old_val, new_val, old_val != new_val))
        return rows

    def feature_profile_sets(self) -> tuple[set[str], set[str], set[str]]:
        old_f = set(self.drift.feature_profile_old.keys()) if self.drift.feature_profile_old else set()
        new_f = set(self.drift.feature_profile_new.keys()) if self.drift.feature_profile_new else set()
        return new_f - old_f, old_f - new_f, old_f & new_f

    def section_map_parsed(self) -> dict[str, tuple[tuple[int, int], tuple[int, int]]]:
        old_parsed = {
            m.group(1): (int(m.group(2)), int(m.group(3)))
            for line in self.drift.old_manifest.section_map_raw.split("\n")
            for m in [_SECTION_MAP_RE.match(line.strip())]
            if m
        }
        new_parsed = {
            m.group(1): (int(m.group(2)), int(m.group(3)))
            for line in self.drift.new_manifest.section_map_raw.split("\n")
            for m in [_SECTION_MAP_RE.match(line.strip())]
            if m
        }
        all_nbs = sorted(set(old_parsed) | set(new_parsed))
        return {nb: (old_parsed.get(nb, (0, 0)), new_parsed.get(nb, (0, 0))) for nb in all_nbs}

    def notebook_run_status(self, nb_name: str) -> tuple[str, str]:
        d = self.drift
        old_cells = d.old_manifest.notebooks.get(nb_name, [])
        new_cells = d.new_manifest.notebooks.get(nb_name, [])
        old_timing = d.old_timings.get(nb_name, "")
        new_timing = d.new_timings.get(nb_name, "")

        def _status(timing: str, cells: list[ManifestCell]) -> str:
            if "FAILED" in timing:
                return "FAILED"
            if "SKIPPED" in timing:
                return "SKIPPED"
            if _notebook_has_errors(cells):
                return "ERROR"
            if timing:
                return "OK"
            if cells:
                return "OK"
            return "N/A"

        return _status(old_timing, old_cells), _status(new_timing, new_cells)

    def notebook_timing(self, nb_name: str) -> tuple[str, str]:
        def _seconds(raw: str) -> str:
            if not raw:
                return ""
            m = re.match(r"[\d.]+", raw)
            if m:
                secs = float(m.group())
                return f"{secs:.0f}s" if secs < 60 else f"{secs / 60:.1f}m"
            if "FAILED" in raw:
                m2 = re.search(r"([\d.]+)s", raw)
                return m2.group() if m2 else ""
            return ""

        return _seconds(self.drift.old_timings.get(nb_name, "")), _seconds(self.drift.new_timings.get(nb_name, ""))

    # --- Cell profile helpers ---

    def _cell_profile_index(self, profiles: Optional[Any], nb_name: str) -> dict[str, Any]:
        """Build cell_id -> profile entry index for a notebook."""
        if profiles is None or not hasattr(profiles, "notebooks"):
            return {}
        nb_profile = profiles.notebooks.get(nb_name)
        if nb_profile is None:
            return {}
        return {c.cell_id: c for c in nb_profile.cells}

    def _cell_profile_name_index(self, profiles: Optional[Any], nb_name: str) -> dict[str, Any]:
        """Build cell_name -> profile entry index (fallback matching)."""
        if profiles is None or not hasattr(profiles, "notebooks"):
            return {}
        nb_profile = profiles.notebooks.get(nb_name)
        if nb_profile is None:
            return {}
        return {c.cell_name: c for c in nb_profile.cells}

    def _nb_profile_total(self, profiles: Optional[Any], nb_name: str) -> Optional[float]:
        """Get total_elapsed for a notebook, or None."""
        if profiles is None or not hasattr(profiles, "notebooks"):
            return None
        nb_profile = profiles.notebooks.get(nb_name)
        return nb_profile.total_elapsed if nb_profile else None

    def _cell_timing_annotation(self, cell_name: str, cell_id: str, nb_name: str) -> str:
        """Return timing annotation string for a cell, e.g. '3.2s -> 2.8s (-0.4s)'."""
        old_idx = self._cell_profile_index(self.drift.old_cell_profiles, nb_name)
        new_idx = self._cell_profile_index(self.drift.new_cell_profiles, nb_name)
        # Try by cell_id first, then by name
        old_entry = old_idx.get(cell_id)
        new_entry = new_idx.get(cell_id)
        if old_entry is None:
            old_name_idx = self._cell_profile_name_index(self.drift.old_cell_profiles, nb_name)
            old_entry = old_name_idx.get(cell_name)
        if new_entry is None:
            new_name_idx = self._cell_profile_name_index(self.drift.new_cell_profiles, nb_name)
            new_entry = new_name_idx.get(cell_name)
        if old_entry is None and new_entry is None:
            return ""
        parts = []
        old_sec = old_entry.elapsed_sec if old_entry else None
        new_sec = new_entry.elapsed_sec if new_entry else None
        if old_sec is not None and new_sec is not None:
            delta = new_sec - old_sec
            parts.append(f"{self._fmt_sec(old_sec)} \u2192 {self._fmt_sec(new_sec)} ({self._fmt_delta(delta)})")
        elif old_sec is not None:
            parts.append(f"old: {self._fmt_sec(old_sec)}")
        elif new_sec is not None:
            parts.append(f"new: {self._fmt_sec(new_sec)}")
        return " \u2014 ".join(parts) if parts else ""

    def _nb_timing_annotation(self, nb_name: str) -> str:
        """Return notebook-level profile timing, e.g. '45.2s -> 38.1s (-7.1s)'."""
        old_total = self._nb_profile_total(self.drift.old_cell_profiles, nb_name)
        new_total = self._nb_profile_total(self.drift.new_cell_profiles, nb_name)
        if old_total is None and new_total is None:
            return ""
        if old_total is not None and new_total is not None:
            delta = new_total - old_total
            return f"{self._fmt_sec(old_total)} \u2192 {self._fmt_sec(new_total)} ({self._fmt_delta(delta)})"
        if old_total is not None:
            return f"old: {self._fmt_sec(old_total)}"
        return f"new: {self._fmt_sec(new_total)}"  # type: ignore[arg-type]

    @staticmethod
    def _fmt_sec(seconds: float) -> str:
        if seconds < 60:
            return f"{seconds:.1f}s"
        return f"{seconds / 60:.1f}m"

    @staticmethod
    def _fmt_delta(delta: float) -> str:
        if abs(delta) < 60:
            return f"{delta:+.1f}s"
        return f"{delta / 60:+.1f}m"

    def grid_dates_summary(self) -> Optional[str]:
        sg_old, sg_new = self.drift.snapshot_grid_old, self.drift.snapshot_grid_new
        if not sg_old and not sg_new:
            return None
        old_dates = sg_old.get("grid_dates", []) if sg_old else []
        new_dates = sg_new.get("grid_dates", []) if sg_new else []
        parts = [f"Grid dates: {len(old_dates)} (old) vs {len(new_dates)} (new)"]
        if old_dates and new_dates and (old_dates[0] != new_dates[0] or old_dates[-1] != new_dates[-1]):
            parts.append(f"Range: [{old_dates[0]} .. {old_dates[-1]}] -> [{new_dates[0]} .. {new_dates[-1]}]")
        return "\n".join(parts)

    def metric_comparison_data(self) -> list[dict[str, Any]]:
        enriched = []
        for item in self.drift.metric_tables:
            old_df, new_df = item["old_df"], item["new_df"]
            entry: dict[str, Any] = {**item, "merged_df": None, "warnings": []}
            if old_df is not None and new_df is not None and pd is not None:
                model_col = next((c for c in old_df.columns if "model" in c.lower() or "name" in c.lower()), None)
                if model_col:
                    merged = old_df.merge(new_df, on=model_col, suffixes=(" (old)", " (new)"), how="outer")
                    for base_col in old_df.columns:
                        if base_col == model_col:
                            continue
                        old_c, new_c = f"{base_col} (old)", f"{base_col} (new)"
                        if old_c in merged.columns and new_c in merged.columns:
                            try:
                                merged[f"{base_col} delta"] = (
                                    merged[new_c].astype(float) - merged[old_c].astype(float)
                                ).round(4)
                            except (ValueError, TypeError):
                                pass
                    entry["merged_df"] = merged
                    for base_col in old_df.columns:
                        delta_col = f"{base_col} delta"
                        if delta_col in merged.columns:
                            try:
                                min_delta = merged[delta_col].min()
                                if min_delta < -_REGRESSION_THRESHOLD:
                                    entry["warnings"].append(f"REGRESSION: {base_col} dropped by {abs(min_delta):.4f}")
                                elif min_delta < -_DRIFT_THRESHOLD:
                                    entry["warnings"].append(f"DRIFT: {base_col} shifted by {abs(min_delta):.4f}")
                            except (ValueError, TypeError):
                                pass
            enriched.append(entry)
        return enriched


