def _is_jupyter_default_id(cell_id: str) -> bool:
    return bool(_JUPYTER_DEFAULT_ID_RE.match(cell_id))


def _compute_diff(old_content: str, new_content: str) -> str:
    return "\n".join(difflib.unified_diff(old_content.split("\n"), new_content.split("\n"), lineterm="", n=3))


def _pair_lists(
    old_list: list[tuple[int, ManifestCell]],
    new_list: list[tuple[int, ManifestCell]],
    matched_old: set[int],
    matched_new: set[int],
    results: list[CellMatch],
) -> None:
    for i in range(min(len(old_list), len(new_list))):
        oidx, oc = old_list[i]
        nidx, nc = new_list[i]
        matched_old.add(oidx)
        matched_new.add(nidx)
        if oc.content == nc.content:
            results.append(CellMatch(oc, nc, CellMatchStatus.RENAMED, ""))
        else:
            results.append(CellMatch(oc, nc, CellMatchStatus.MODIFIED, _compute_diff(oc.content, nc.content)))


def _positional_pair(
    leftover_old: list[tuple[int, ManifestCell]],
    leftover_new: list[tuple[int, ManifestCell]],
    matched_old: set[int],
    matched_new: set[int],
    results: list[CellMatch],
) -> None:
    new_sections = {c.section for _, c in leftover_new if c.section}
    old_sections = {c.section for _, c in leftover_old if c.section}
    shared_sections = old_sections & new_sections
    if shared_sections:
        for section in sorted(shared_sections):
            sec_old = [(i, c) for i, c in leftover_old if c.section == section and i not in matched_old]
            sec_new = [(i, c) for i, c in leftover_new if c.section == section and i not in matched_new]
            _pair_lists(sec_old, sec_new, matched_old, matched_new, results)
        remaining_old = [(i, c) for i, c in leftover_old if i not in matched_old]
        remaining_new = [(i, c) for i, c in leftover_new if i not in matched_new]
        _pair_lists(remaining_old, remaining_new, matched_old, matched_new, results)
    else:
        _pair_lists(leftover_old, leftover_new, matched_old, matched_new, results)


def match_cells(old_cells: list[ManifestCell], new_cells: list[ManifestCell]) -> list[CellMatch]:
    matched_old: set[int] = set()
    matched_new: set[int] = set()
    results: list[CellMatch] = []

    old_by_id: dict[str, tuple[int, ManifestCell]] = {}
    for idx, c in enumerate(old_cells):
        if not _is_jupyter_default_id(c.cell_id):
            old_by_id[c.cell_id] = (idx, c)

    for nidx, nc in enumerate(new_cells):
        if _is_jupyter_default_id(nc.cell_id):
            continue
        if nc.cell_id in old_by_id:
            oidx, oc = old_by_id[nc.cell_id]
            matched_old.add(oidx)
            matched_new.add(nidx)
            if oc.content == nc.content and oc.name == nc.name:
                results.append(CellMatch(oc, nc, CellMatchStatus.UNCHANGED, ""))
            elif oc.content == nc.content:
                results.append(CellMatch(oc, nc, CellMatchStatus.RENAMED, ""))
            else:
                diff = _compute_diff(oc.content, nc.content)
                status = CellMatchStatus.RENAMED if oc.name != nc.name else CellMatchStatus.MODIFIED
                results.append(CellMatch(oc, nc, status, diff))

    remaining_old: dict[str, tuple[int, ManifestCell]] = {}
    for idx, c in enumerate(old_cells):
        if idx not in matched_old:
            remaining_old[c.name] = (idx, c)

    for nidx, nc in enumerate(new_cells):
        if nidx in matched_new:
            continue
        if nc.name in remaining_old:
            oidx, oc = remaining_old.pop(nc.name)
            matched_old.add(oidx)
            matched_new.add(nidx)
            if oc.content == nc.content:
                results.append(CellMatch(oc, nc, CellMatchStatus.UNCHANGED, ""))
            else:
                results.append(CellMatch(oc, nc, CellMatchStatus.MODIFIED, _compute_diff(oc.content, nc.content)))

    leftover_old = [(idx, c) for idx, c in enumerate(old_cells) if idx not in matched_old]
    leftover_new = [(idx, c) for idx, c in enumerate(new_cells) if idx not in matched_new]
    _positional_pair(leftover_old, leftover_new, matched_old, matched_new, results)

    for idx, c in enumerate(old_cells):
        if idx not in matched_old:
            results.append(CellMatch(c, None, CellMatchStatus.REMOVED, ""))
    for idx, c in enumerate(new_cells):
        if idx not in matched_new:
            results.append(CellMatch(None, c, CellMatchStatus.ADDED, ""))

    return results


