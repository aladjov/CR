def compute_drift_result(
    old_manifest_path: Path,
    new_manifest_path: Path,
    old_run_dir: Optional[Path],
    new_run_dir: Optional[Path],
) -> DriftResult:
    old_m = parse_manifest(old_manifest_path.read_text(encoding="utf-8"))
    new_m = parse_manifest(new_manifest_path.read_text(encoding="utf-8"))
    old_meta = _read_run_metadata(old_run_dir)
    new_meta = _read_run_metadata(new_run_dir)

    all_nbs = sorted(old_m.notebook_names | new_m.notebook_names)
    notebook_drifts = []
    for nb in all_nbs:
        old_cells = old_m.notebooks.get(nb, [])
        new_cells = new_m.notebooks.get(nb, [])
        matches = match_cells(old_cells, new_cells)
        notebook_drifts.append(NotebookDrift(nb, matches))

    sg_old = sg_new = pc_old = pc_new = fp_old = fp_new = None
    old_timings: dict[str, str] = {}
    new_timings: dict[str, str] = {}
    if old_run_dir and new_run_dir:
        sg_old = _load_yaml(old_run_dir / "snapshot_grid.yaml")
        sg_new = _load_yaml(new_run_dir / "snapshot_grid.yaml")
        pc_old = _load_yaml(old_run_dir / "project_context.yaml")
        pc_new = _load_yaml(new_run_dir / "project_context.yaml")
        fp_old = _load_yaml(old_run_dir / "merged" / "exploration_feature_profile.yaml")
        fp_new = _load_yaml(new_run_dir / "merged" / "exploration_feature_profile.yaml")
        for run_dir, target in [(old_run_dir, "old_timings"), (new_run_dir, "new_timings")]:
            for base in [
                run_dir,
                run_dir / "notebooks",
                run_dir.parent.parent / "exploration_notebooks",
                run_dir.parent.parent,
            ]:
                log = base / "run_exploration.log"
                if log.exists():
                    if target == "old_timings":
                        old_timings = _parse_timing_log(log)
                    else:
                        new_timings = _parse_timing_log(log)
                    break

    # Load cell profiles if available
    old_cell_profiles = None
    new_cell_profiles = None
    if load_cell_profiles is not None:
        if old_run_dir:
            old_cell_profiles = load_cell_profiles(old_run_dir / "cell_profiles.json")
        if new_run_dir:
            new_cell_profiles = load_cell_profiles(new_run_dir / "cell_profiles.json")

    return DriftResult(
        old_meta=old_meta,
        new_meta=new_meta,
        old_manifest=old_m,
        new_manifest=new_m,
        notebook_drifts=notebook_drifts,
        snapshot_grid_old=sg_old,
        snapshot_grid_new=sg_new,
        project_context_old=pc_old,
        project_context_new=pc_new,
        feature_profile_old=fp_old,
        feature_profile_new=fp_new,
        old_timings=old_timings,
        new_timings=new_timings,
        metric_tables=_build_metric_comparisons(old_m, new_m),
        old_cell_profiles=old_cell_profiles,
        new_cell_profiles=new_cell_profiles,
    )


