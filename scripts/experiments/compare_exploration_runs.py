def _load_yaml(path: Path) -> Optional[dict]:
    if yaml is None or not path.exists():
        return None
    with open(path, encoding="utf-8") as f:
        return yaml.safe_load(f)


def _extract_html_tables(cell_content: str) -> list:
    if pd is None:
        return []
    tables = re.findall(r"<table[\s\S]*?</table>", cell_content, re.IGNORECASE)
    result = []
    for t in tables:
        try:
            result.extend(pd.read_html(io.StringIO(t)))
        except Exception:
            pass
    return result


def _find_metric_tables(manifest: ParsedManifest, nb_name: str = "08_baseline_experiments") -> list:
    cells = manifest.notebooks.get(nb_name, [])
    result = []
    for cell in cells:
        for df in _extract_html_tables(cell.content):
            cols = [c.lower() for c in df.columns]
            if any("auc" in c or "f1" in c for c in cols):
                result.append((cell.name, df))
    return result


def _read_run_metadata(run_dir: Optional[Path]) -> RunMetadata:
    if run_dir is None:
        return RunMetadata("unknown", "unknown", "unknown")
    meta = {"sha": "unknown", "version": "unknown", "date": "unknown"}
    for key, filename in [("sha", "git_sha.txt"), ("version", "version.txt"), ("date", "commit_date.txt")]:
        p = run_dir / filename
        if p.exists():
            meta[key] = p.read_text(encoding="utf-8").strip()
    if meta["sha"] != "unknown":
        meta["sha"] = meta["sha"][:7]
    return RunMetadata(**meta)


_LOG_OK_RE = re.compile(r"\s*\[?(\w+)\]?\s+.*?OK\s+\((\d+\.?\d*)s\)")
_LOG_FAIL_RE = re.compile(r"\s*---\s*Notebook:\s*(\w+)\s*\|.*?\((\d+\.?\d*)s\)\s*---")
_LOG_STATUS_RE = re.compile(r"\s*\[?(\w+)\]?\s+.*?(FAILED|SKIPPED)")


def _parse_timing_log(path: Path) -> dict[str, str]:
    if not path.exists():
        return {}
    timings: dict[str, str] = {}
    for line in path.read_text(encoding="utf-8").split("\n"):
        m = _LOG_OK_RE.match(line)
        if m:
            timings[m.group(1)] = m.group(2)
            continue
        m = _LOG_FAIL_RE.match(line)
        if m:
            timings[m.group(1)] = f"FAILED ({m.group(2)}s)"
            continue
        m = _LOG_STATUS_RE.match(line)
        if m:
            timings[m.group(1)] = m.group(2)
    return timings


def _notebook_has_errors(cells: list[ManifestCell]) -> bool:
    return any("### Error:" in c.content for c in cells)


def _build_metric_comparisons(old_manifest: ParsedManifest, new_manifest: ParsedManifest) -> list:
    old_tables = _find_metric_tables(old_manifest)
    new_tables = _find_metric_tables(new_manifest)
    if not old_tables and not new_tables:
        return []
    result = []
    for old_item, new_item in zip(
        old_tables or [(None, None)], new_tables or [(None, None)]
    ):
        old_name, old_df = old_item if old_item else (None, None)
        new_name, new_df = new_item if new_item else (None, None)
        result.append({"old_name": old_name, "old_df": old_df, "new_name": new_name, "new_df": new_df})
    return result


