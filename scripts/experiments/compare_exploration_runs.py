# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------

_DRIFT_THRESHOLD = 0.005
_REGRESSION_THRESHOLD = 0.01
_JUPYTER_DEFAULT_ID_RE = re.compile(r"^cell-\d+$")
_NB_HEADER_RE = re.compile(r"^# (\S+)\s*$", re.MULTILINE)
_CELL_HEADER_RE = re.compile(
    r"^## (?:code|config):\s*(\S+)\s+\(id:\s*([\w-]+)\)(?:\s+\(section:\s*([^\)]+)\))?",
    re.MULTILINE,
)
_SECTION_MAP_RE = re.compile(r"<!--\s*(\S+)\s+\((\d+)\s+cells,\s+(\d+)\s+with output\)\s*-->")
_CELL_CONTENT_MAX = 500


# ---------------------------------------------------------------------------
# Data Layer
# ---------------------------------------------------------------------------


class CellMatchStatus(str, Enum):
    UNCHANGED = "unchanged"
    MODIFIED = "modified"
    ADDED = "added"
    REMOVED = "removed"
    RENAMED = "renamed"


@dataclass(frozen=True)
class ManifestCell:
    name: str
    cell_id: str
    section: str
    content: str


@dataclass
class ParsedManifest:
    notebooks: dict[str, list[ManifestCell]]
    section_map_raw: str

    @property
    def notebook_names(self) -> set[str]:
        return set(self.notebooks)

    def cells_by_id(self, notebook: str) -> dict[str, ManifestCell]:
        return {c.cell_id: c for c in self.notebooks.get(notebook, [])}

    def cells_by_name(self, notebook: str) -> dict[str, ManifestCell]:
        return {c.name: c for c in self.notebooks.get(notebook, [])}


@dataclass(frozen=True)
class RunMetadata:
    sha: str
    version: str
    date: str

    @property
    def label(self) -> str:
        return f"{self.sha}  v{self.version}  ({self.date})"


@dataclass(frozen=True)
class CellMatch:
    old_cell: Optional[ManifestCell]
    new_cell: Optional[ManifestCell]
    status: CellMatchStatus
    diff_text: str


@dataclass
class NotebookDrift:
    notebook_name: str
    cell_matches: list[CellMatch]

    @property
    def has_changes(self) -> bool:
        return any(m.status != CellMatchStatus.UNCHANGED for m in self.cell_matches)

    @property
    def changed_matches(self) -> list[CellMatch]:
        return [m for m in self.cell_matches if m.status != CellMatchStatus.UNCHANGED]


@dataclass
class DriftResult:
    old_meta: RunMetadata
    new_meta: RunMetadata
    old_manifest: ParsedManifest
    new_manifest: ParsedManifest
    notebook_drifts: list[NotebookDrift]
    snapshot_grid_old: Optional[dict]
    snapshot_grid_new: Optional[dict]
    project_context_old: Optional[dict]
    project_context_new: Optional[dict]
    feature_profile_old: Optional[dict]
    feature_profile_new: Optional[dict]
    old_timings: dict[str, str]
    new_timings: dict[str, str]
    metric_tables: list = field(default_factory=list)


# ---------------------------------------------------------------------------
# Manifest Parsing
# ---------------------------------------------------------------------------


def parse_manifest(text: str) -> ParsedManifest:
    section_map_lines = []
    for line in text.split("\n"):
        if line.startswith("<!--"):
            section_map_lines.append(line)
        elif line.strip() and not line.startswith("<!--"):
            break
    section_map_raw = "\n".join(section_map_lines)

    notebooks: dict[str, list[ManifestCell]] = {}
    parts = _NB_HEADER_RE.split(text)
    i = 1
    while i < len(parts) - 1:
        nb_name = parts[i].strip()
        nb_body = parts[i + 1]
        i += 2
        cells: list[ManifestCell] = []
        cell_parts = _CELL_HEADER_RE.split(nb_body)
        j = 1
        while j < len(cell_parts) - 3:
            name = cell_parts[j]
            cell_id = cell_parts[j + 1]
            section = cell_parts[j + 2] or ""
            content = cell_parts[j + 3].strip()
            cells.append(ManifestCell(name=name, cell_id=cell_id, section=section, content=content))
            j += 4
        notebooks[nb_name] = cells
    return ParsedManifest(notebooks=notebooks, section_map_raw=section_map_raw)


