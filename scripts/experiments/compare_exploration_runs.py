# CLI
# ---------------------------------------------------------------------------


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate exploration drift report.")
    parser.add_argument("--old-manifest", type=Path, required=True)
    parser.add_argument("--new-manifest", type=Path, required=True)
    parser.add_argument("--old-run-dir", type=Path, default=None)
    parser.add_argument("--new-run-dir", type=Path, default=None)
    parser.add_argument("--output", type=Path, default=None, help="Output file (default: stdout)")
    parser.add_argument("--format", choices=["md", "html", "both"], default="both", dest="fmt")
    args = parser.parse_args()

    drift = compute_drift_result(args.old_manifest, args.new_manifest, args.old_run_dir, args.new_run_dir)
    renderers = {"md": MarkdownDriftRenderer, "html": HtmlDriftRenderer}
    formats = ["md", "html"] if args.fmt == "both" else [args.fmt]

    for fmt in formats:
        report = renderers[fmt](drift).render()
        if args.output:
            suffix = ".html" if fmt == "html" else ".md"
            out_path = args.output.with_suffix(suffix)
            out_path.parent.mkdir(parents=True, exist_ok=True)
            out_path.write_text(report, encoding="utf-8")
            print(f"Drift report written to {out_path}", file=sys.stderr)
        else:
            print(report)


if __name__ == "__main__":
    main()
