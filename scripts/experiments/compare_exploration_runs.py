def generate_drift_report(
    old_manifest_path: Path,
    new_manifest_path: Path,
    old_run_dir: Optional[Path],
    new_run_dir: Optional[Path],
) -> str:
    drift = compute_drift_result(old_manifest_path, new_manifest_path, old_run_dir, new_run_dir)
    return MarkdownDriftRenderer(drift).render()


