class MarkdownDriftRenderer(DriftReportRenderer):
    def join_sections(self, sections: Iterable[str]) -> str:
        return "\n\n".join(s for s in sections if s) + "\n"

    def render_title(self) -> str:
        return f"# Drift Report: {self.drift.old_meta.sha} -> {self.drift.new_meta.sha}"

    def render_summary(self) -> str:
        d = self.drift
        old_nb = len(d.old_manifest.notebooks)
        new_nb = len(d.new_manifest.notebooks)
        return (
            f"## Summary\n"
            f"- Old: {d.old_meta.label}\n"
            f"- New: {d.new_meta.label}\n"
            f"- Notebooks captured: {old_nb} (old), {new_nb} (new)"
        )

    def _status_icon(self, status: str) -> str:
        return {"OK": "\u2705", "FAILED": "\u274c", "ERROR": "\u26a0\ufe0f", "SKIPPED": "\u23ed", "N/A": "\u2014"}.get(
            status, status
        )

    def render_section_map_changes(self) -> str:
        rows = [
            "| Notebook | Old status | New status | Old cells (outputs) | New cells (outputs) | Cell delta | Output delta |",
            "|----------|-----------|-----------|--------------------|--------------------|------------|--------------|",
        ]
        for nb, ((oc, oo), (nc, no)) in self.section_map_parsed().items():
            old_st, new_st = self.notebook_run_status(nb)
            cd = nc - oc if oc or nc else "N/A"
            od = no - oo if oc or nc else "N/A"
            rows.append(
                f"| {nb} | {self._status_icon(old_st)} {old_st} | {self._status_icon(new_st)} {new_st} | {oc} ({oo}) | {nc} ({no}) | {cd} | {od} |"
            )
        return "## Section Map Changes\n\n" + "\n".join(rows)

    def render_model_metrics(self) -> str:
        data = self.metric_comparison_data()
        if not data:
            return "## Model Metrics (NB08)\n\n_No metric tables found in either run._"
        parts = ["## Model Metrics (NB08)"]
        for entry in data:
            if entry["merged_df"] is not None:
                parts.append(entry["merged_df"].to_markdown(index=False))
                for w in entry["warnings"]:
                    parts.append(f"\n\u26a0 **{w}**")
            elif entry["old_df"] is not None:
                parts.append(f"**Old only ({entry['old_name']}):**\n{entry['old_df'].to_markdown(index=False)}")
            elif entry["new_df"] is not None:
                parts.append(f"**New only ({entry['new_name']}):**\n{entry['new_df'].to_markdown(index=False)}")
        return "\n\n".join(parts)

    def _render_yaml_section(
        self, title: str, old_d: Optional[dict], new_d: Optional[dict], keys: list[str], extra: str = ""
    ) -> str:
        if old_d is None and new_d is None:
            return f"## {title}\n\n_Not available._"
        rows = ["| Parameter | Old | New | Changed |", "|-----------|-----|-----|---------|"]
        for key, ov, nv, changed in self.yaml_diff_rows(old_d, new_d, keys):
            flag = "\u26a0" if changed else ""
            rows.append(f"| {key} | {ov} | {nv} | {flag} |")
        result = f"## {title}\n\n" + "\n".join(rows)
        if extra:
            result += f"\n\n{extra}"
        return result

    def render_snapshot_grid(self) -> str:
        return self._render_yaml_section(
            "Snapshot Grid",
            self.drift.snapshot_grid_old,
            self.drift.snapshot_grid_new,
            self.SNAPSHOT_GRID_KEYS,
            self.grid_dates_summary() or "",
        )

    def render_project_context(self) -> str:
        return self._render_yaml_section(
            "Project Context / Intent",
            self.drift.project_context_old,
            self.drift.project_context_new,
            self.PROJECT_CONTEXT_KEYS,
        )

    def render_feature_profile(self) -> str:
        added, removed, common = self.feature_profile_sets()
        if not added and not removed and not common:
            return "## Feature Profile\n\n_Not found in either run._"
        parts = [
            "## Feature Profile",
            f"- Old features: {len(removed) + len(common)}",
            f"- New features: {len(added) + len(common)}",
            f"- Added: {len(added)}, Removed: {len(removed)}, Common: {len(common)}",
        ]
        if added:
            parts.append(f"\n**Added:** {', '.join(sorted(added)[:20])}")
        if removed:
            parts.append(f"\n**Removed:** {', '.join(sorted(removed)[:20])}")
        return "\n".join(parts)

    def render_timing(self) -> str:
        ot, nt = self.drift.old_timings, self.drift.new_timings
        if not ot and not nt:
            return "## Per-Notebook Timing\n\n_No timing logs found._"
        rows = ["| Notebook | Old | New | Delta |", "|----------|-----|-----|-------|"]
        for nb in dict.fromkeys(list(ot) + list(nt)):
            ov, nv = ot.get(nb, "N/A"), nt.get(nb, "N/A")
            try:
                delta = f"{float(nv) - float(ov):+.1f}s"
            except (ValueError, TypeError):
                delta = "N/A"
            rows.append(f"| {nb} | {ov} | {nv} | {delta} |")
        table = "\n".join(rows)
        return f"## Per-Notebook Timing\n\n<details>\n<summary>Show timing table</summary>\n\n{table}\n\n</details>"

    def render_cell_profiling(self) -> str:
        op, np_ = self.drift.old_cell_profiles, self.drift.new_cell_profiles
        if op is None and np_ is None:
            return "## Per-Cell Profiling\n\n_No cell profiles found._"
        parts = ["## Per-Cell Profiling"]
        # Determine which columns have data
        has_spark = False
        has_mem = False
        for profiles in [op, np_]:
            if profiles is None:
                continue
            for nb_prof in profiles.notebooks.values():
                for c in nb_prof.cells:
                    if c.spark_jobs is not None:
                        has_spark = True
                    if c.peak_memory_mb is not None:
                        has_mem = True
        # Cross-environment note
        if op and np_ and op.environment != np_.environment:
            parts.append(
                f"\n> _Cross-environment comparison ({op.environment} vs {np_.environment}) "
                f"\u2014 elapsed times reflect different hardware._\n"
            )

        all_nbs = sorted(set(list(op.notebooks if op else {}) + list(np_.notebooks if np_ else {})))
        for nb_name in all_nbs:
            nb_annotation = self._nb_timing_annotation(nb_name)
            summary = nb_name
            if nb_annotation:
                summary += f" ({nb_annotation})"

            cols = ["Cell Name", "Cell ID", "Old", "New", "Delta"]
            if has_spark:
                cols.append("Spark Jobs")
            if has_mem:
                cols.append("Mem MB")
            header_row = "| " + " | ".join(cols) + " |"
            sep_row = "|" + "|".join("---" for _ in cols) + "|"

            old_idx = self._cell_profile_index(op, nb_name)
            new_idx = self._cell_profile_index(np_, nb_name)
            old_name_idx = self._cell_profile_name_index(op, nb_name)
            new_name_idx = self._cell_profile_name_index(np_, nb_name)

            # Collect all cells in order (new side order, then old-only)
            seen_ids: set[str] = set()
            ordered_cells: list[tuple[str, str]] = []  # (cell_name, cell_id)
            for profiles in [np_, op]:
                if profiles is None:
                    continue
                nb_prof = profiles.notebooks.get(nb_name)
                if nb_prof is None:
                    continue
                for c in nb_prof.cells:
                    if c.cell_id not in seen_ids:
                        seen_ids.add(c.cell_id)
                        ordered_cells.append((c.cell_name, c.cell_id))

            rows = [header_row, sep_row]
            for cell_name, cell_id in ordered_cells:
                old_e = old_idx.get(cell_id) or old_name_idx.get(cell_name)
                new_e = new_idx.get(cell_id) or new_name_idx.get(cell_name)
                old_sec = old_e.elapsed_sec if old_e else None
                new_sec = new_e.elapsed_sec if new_e else None

                old_str = self._fmt_sec(old_sec) if old_sec is not None else "\u2014"
                new_str = self._fmt_sec(new_sec) if new_sec is not None else "\u2014"
                if old_sec is not None and new_sec is not None:
                    delta_str = self._fmt_delta(new_sec - old_sec)
                else:
                    delta_str = "\u2014"

                row_parts = [cell_name, cell_id[:8], old_str, new_str, delta_str]
                if has_spark:
                    old_sj = str(old_e.spark_jobs) if old_e and old_e.spark_jobs is not None else "\u2014"
                    new_sj = str(new_e.spark_jobs) if new_e and new_e.spark_jobs is not None else "\u2014"
                    row_parts.append(f"{old_sj}/{new_sj}")
                if has_mem:
                    old_mm = f"{old_e.peak_memory_mb:.1f}" if old_e and old_e.peak_memory_mb is not None else "\u2014"
                    new_mm = f"{new_e.peak_memory_mb:.1f}" if new_e and new_e.peak_memory_mb is not None else "\u2014"
                    row_parts.append(f"{old_mm}/{new_mm}")
                rows.append("| " + " | ".join(row_parts) + " |")
            table = "\n".join(rows)
            parts.append(f"<details>\n<summary>{summary}</summary>\n\n{table}\n\n</details>")
        return "\n\n".join(parts)

    def render_cell_by_cell_diff(self) -> str:
        parts = ["## Cell-by-Cell Diff"]
        any_diff = False
        for nd in self.drift.notebook_drifts:
            old_st, new_st = self.notebook_run_status(nd.notebook_name)
            old_time, new_time = self.notebook_timing(nd.notebook_name)
            old_part = (
                f"{self._status_icon(old_st)} {old_st} ({old_time})"
                if old_time
                else f"{self._status_icon(old_st)} {old_st}"
            )
            new_part = (
                f"{self._status_icon(new_st)} {new_st} ({new_time})"
                if new_time
                else f"{self._status_icon(new_st)} {new_st}"
            )
            status_line = f"Old: {old_part} | New: {new_part}"
            if not nd.has_changes:
                continue
            any_diff = True
            nb_timing = self._nb_timing_annotation(nd.notebook_name)
            nb_header = f"### {nd.notebook_name}"
            if nb_timing:
                nb_header += f" ({nb_timing})"
            nb_parts = [f"---\n\n{nb_header}\n\n> {status_line}"]
            for m in nd.changed_matches:
                cell = m.new_cell or m.old_cell
                name = cell.name
                cell_id = cell.cell_id
                label = m.status.value.upper()
                timing_ann = self._cell_timing_annotation(name, cell_id, nd.notebook_name)
                cell_header = f"#### {name} ({label})"
                if timing_ann:
                    cell_header += f" \u2014 {timing_ann}"
                nb_parts.append(cell_header)
                if m.status == CellMatchStatus.ADDED:
                    nb_parts.append(f"```\n{m.new_cell.content[:_CELL_CONTENT_MAX]}\n```")
                elif m.status == CellMatchStatus.REMOVED:
                    nb_parts.append(f"```\n{m.old_cell.content[:_CELL_CONTENT_MAX]}\n```")
                elif m.diff_text:
                    nb_parts.append(f"```diff\n{m.diff_text}\n```")
                elif m.status == CellMatchStatus.RENAMED:
                    nb_parts.append(f"_Renamed from `{m.old_cell.name}` to `{m.new_cell.name}`_")
            parts.append("\n\n".join(nb_parts))
        if not any_diff:
            parts.append("_No cell-level differences detected._")
        return "\n\n".join(parts)


